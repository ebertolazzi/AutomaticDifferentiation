#include "gradient_benchmark_common.hpp"

#include <filesystem>
#include <fstream>
#include <iostream>
#include <limits>
#include <stdexcept>
#include <string>

namespace {

std::filesystem::path default_runtime_dir() {
#ifdef AUTODIFF_CODEGEN_RUNTIME_DIR
  return AUTODIFF_CODEGEN_RUNTIME_DIR;
#else
  return std::filesystem::current_path() / "cppadcg_benchmark_runtime";
#endif
}

std::string model_name() {
#ifdef AUTODIFF_CODEGEN_MODEL_NAME
  return AUTODIFF_CODEGEN_MODEL_NAME;
#else
  return "autodiff_codegen_model";
#endif
}

std::filesystem::path parse_output_dir(int argc, char** argv) {
  std::filesystem::path out_dir = default_runtime_dir();

  for (int i = 1; i < argc; ++i) {
    const std::string arg(argv[i]);
    if (arg == "--output-dir" && i + 1 < argc) {
      out_dir = argv[++i];
    } else if (arg == "--help") {
      std::cout << "Usage: " << argv[0] << " [--output-dir PATH]\n";
      std::exit(0);
    } else {
      throw std::runtime_error("Unknown argument: " + arg);
    }
  }

  return out_dir;
}

void remove_previous_generated_files(const std::filesystem::path& out_dir) {
  if (!std::filesystem::exists(out_dir)) {
    return;
  }

  for (const auto& entry : std::filesystem::directory_iterator(out_dir)) {
    if (!entry.is_regular_file()) {
      continue;
    }

    const auto ext = entry.path().extension().string();
    if (ext == ".c" || ext == ".txt" || ext == ".cmake") {
      std::filesystem::remove(entry.path());
    }
  }
}

void write_runtime_cmakelists(const std::filesystem::path& out_dir, const std::string& output_name) {
  std::ofstream os(out_dir / "CMakeLists.txt");
  os
    << "cmake_minimum_required(VERSION 3.16)\n"
    << "project(" << output_name << " LANGUAGES C)\n\n"
    << "file(GLOB CPPADCG_GENERATED_SOURCES CONFIGURE_DEPENDS \"${CMAKE_CURRENT_SOURCE_DIR}/*.c\")\n"
    << "add_library(" << output_name << " SHARED ${CPPADCG_GENERATED_SOURCES})\n"
    << "target_compile_options(" << output_name << " PRIVATE\n"
    << "  $<$<OR:$<C_COMPILER_ID:GNU>,$<C_COMPILER_ID:Clang>>:-O2>\n"
    << "  $<$<C_COMPILER_ID:MSVC>:/O2>\n"
    << ")\n"
    << "target_compile_definitions(" << output_name << " PRIVATE NDEBUG)\n"
    << "set_target_properties(" << output_name << " PROPERTIES\n"
    << "  OUTPUT_NAME \"" << output_name << "\"\n"
    << "  LIBRARY_OUTPUT_DIRECTORY \"${CMAKE_BINARY_DIR}\"\n"
    << "  ARCHIVE_OUTPUT_DIRECTORY \"${CMAKE_BINARY_DIR}\"\n"
    << "  RUNTIME_OUTPUT_DIRECTORY \"${CMAKE_BINARY_DIR}\"\n"
    << ")\n"
    << "foreach(cfg ${CMAKE_CONFIGURATION_TYPES})\n"
    << "  string(TOUPPER \"${cfg}\" cfg_upper)\n"
    << "  set_target_properties(" << output_name << " PROPERTIES\n"
    << "    LIBRARY_OUTPUT_DIRECTORY_${cfg_upper} \"${CMAKE_BINARY_DIR}\"\n"
    << "    ARCHIVE_OUTPUT_DIRECTORY_${cfg_upper} \"${CMAKE_BINARY_DIR}\"\n"
    << "    RUNTIME_OUTPUT_DIRECTORY_${cfg_upper} \"${CMAKE_BINARY_DIR}\"\n"
    << "  )\n"
    << "endforeach()\n";
}

void write_manifest(const std::filesystem::path& out_dir) {
  std::ofstream os(out_dir / "README.txt");
  os << "Generated by gradient_benchmark_generate.\n";
  os << "Build this directory with CMake to obtain the shared library used by gradient_benchmark.\n";
}

}  // namespace

int main(int argc, char** argv) {
  try {
    namespace fs = std::filesystem;
    using namespace CppAD::cg;

    const fs::path out_dir = parse_output_dir(argc, argv);
    const std::string name = model_name();

    fs::create_directories(out_dir);
    remove_previous_generated_files(out_dir);

    auto fun = autodiff_benchmark::build_cppadcg_tape();

    ModelCSourceGen<double> cgen(fun, name);
    cgen.setCreateForwardZero(true);
    cgen.setCreateJacobian(true);
    cgen.setMaxAssignmentsPerFunc(0);
    cgen.setMaxOperationsPerAssignment((std::numeric_limits<size_t>::max)());

    ModelLibraryCSourceGen<double> libgen(cgen);
    libgen.setMultiThreading(MultiThreadingType::NONE);
    SaveFilesModelLibraryProcessor<double>::saveLibrarySourcesTo(libgen, out_dir.string());

    write_runtime_cmakelists(out_dir, name);
    write_manifest(out_dir);

    std::size_t file_count = 0;
    for (const auto& entry : fs::directory_iterator(out_dir)) {
      if (entry.is_regular_file() && entry.path().extension() == ".c") {
        ++file_count;
      }
    }

    std::cout << "Generated " << file_count << " C sources in " << out_dir << '\n';
    return 0;
  } catch (const std::exception& err) {
    std::cerr << "Error: " << err.what() << '\n';
    return 1;
  }
}
